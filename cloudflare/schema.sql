PRAGMA foreign_keys=ON;
CREATE TABLE IF NOT EXISTS homes (id TEXT PRIMARY KEY, name TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS users (chat TEXT PRIMARY KEY, active INTEGER NOT NULL DEFAULT 0, prefs TEXT NOT NULL, due INTEGER, revision INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS access (chat TEXT REFERENCES users(chat) ON DELETE CASCADE, home TEXT REFERENCES homes(id) ON DELETE CASCADE, PRIMARY KEY(chat,home));
CREATE TABLE IF NOT EXISTS snapshots (home TEXT PRIMARY KEY REFERENCES homes(id) ON DELETE CASCADE, payload TEXT NOT NULL, received INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS events (id TEXT PRIMARY KEY, chat TEXT NOT NULL, created INTEGER NOT NULL, state TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS events_chat_time ON events(chat,created);
CREATE INDEX IF NOT EXISTS users_due ON users(active,due);
